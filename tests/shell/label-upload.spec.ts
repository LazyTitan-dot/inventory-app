import { test, expect } from './adaptation-fixtures';

test('a real label photo is read and selectively applied without saving or replacing the internal barcode', async ({ page, featureData }) => {
  test.setTimeout(90_000);
  featureData.features = [...(featureData.features ?? []), 'barcode_aliases_v1'];
  const unexpected: string[] = [];
  const readingOrigins: string[] = [];
  let reading = false;
  let commandCount = 0;
  page.on('request', (request) => {
    const url = new URL(request.url());
    if (reading) readingOrigins.push(url.origin);
    if (request.url().endsWith('/rpc/retail_command')) commandCount++;
    if (!['http://127.0.0.1:4178', 'https://phase5-fixture.supabase.co', 'https://fonts.googleapis.com', 'https://fonts.gstatic.com'].includes(url.origin)) unexpected.push(url.origin);
  });
  await page.goto('/inventario');
  await page.getByRole('button', { name: 'Agregar producto', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Agregar producto', exact: true });
  await editor.getByRole('textbox', { name: 'Marca', exact: true }).fill('Marca conservada');
  await editor.getByRole('textbox', { name: 'Modelo', exact: true }).fill('Modelo anterior');
  await editor.getByRole('spinbutton', { name: 'Costo (RD$)', exact: true }).fill('100');
  await editor.getByRole('spinbutton', { name: /^Precio final con ITBIS/ }).fill('150');
  await editor.locator('details[data-identification] summary').click();
  const internalCode = await editor.getByRole('textbox', { name: /^Código de barras/ }).inputValue();
  expect(internalCode).toMatch(/^SL/);
  await editor.locator('details[data-identification] summary').click();
  await editor.getByRole('button', { name: 'Escanear etiqueta', exact: true }).click();
  const capture = page.getByRole('dialog', { name: 'Escanear etiqueta', exact: true });
  const photo = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 1600; canvas.height = 1200;
    const context = canvas.getContext('2d')!;
    context.fillStyle = 'white'; context.fillRect(0, 0, canvas.width, canvas.height);
    context.fillStyle = 'black'; context.font = 'bold 70px Arial';
    ['HISENSE', 'Modelo: AC122CE', 'Color: BLANCO', 'Aire acondicionado', 'Capacidad: 12,000 BTU/h', 'Refrigerante: R410A', 'Batch NO. K-83PZ'].forEach((line, index) => context.fillText(line, 70, 100 + index * 110));
    const code = '6946087393113';
    const left = ['0001101','0011001','0010011','0111101','0100011','0110001','0101111','0111011','0110111','0001011'];
    const parity = 'LGGGLL';
    const inverse = (value: string) => [...value].map((bit) => bit === '0' ? '1' : '0').join('');
    let bars = '101';
    for (let i = 1; i <= 6; i++) { const pattern = left[Number(code[i])]!; bars += parity[i - 1] === 'L' ? pattern : [...inverse(pattern)].reverse().join(''); }
    bars += '01010';
    for (let i = 7; i <= 12; i++) bars += inverse(left[Number(code[i])]!);
    bars += '101';
    [...bars].forEach((bar, index) => { if (bar === '1') context.fillRect(150 + index * 10, 920, 10, 200); });
    return canvas.toDataURL('image/png').split(',')[1]!;
  });
  await capture.getByLabel('Foto de la etiqueta', { exact: true }).setInputFiles({ name: 'etiqueta-sintetica.png', mimeType: 'image/png', buffer: Buffer.from(photo, 'base64') });
  reading = true;
  await capture.getByRole('button', { name: 'Leer etiqueta', exact: true }).click();
  await expect(capture.getByRole('heading', { name: 'Revisar datos', exact: true })).toBeVisible({ timeout: 60_000 });
  reading = false;
  expect(readingOrigins.length).toBeGreaterThan(0);
  expect(readingOrigins.every((value) => value === 'http://127.0.0.1:4178')).toBe(true);
  await expect(capture.getByRole('textbox', { name: 'Marca', exact: true })).toHaveValue('Hisense');
  await expect(capture.getByRole('textbox', { name: 'Modelo', exact: true })).toHaveValue('AC122CE');
  await expect(capture.getByRole('textbox', { name: 'Opción o variante', exact: true })).toHaveValue('12,000 BTU · Blanco');
  await expect(capture.getByRole('textbox', { name: 'Código del fabricante', exact: true })).toHaveValue('6946087393113');
  await expect(editor.locator('.catalog-editor-identity').getByRole('textbox', { name: 'Marca', exact: true, includeHidden: true })).toHaveValue('Marca conservada');
  await expect(editor.locator('.catalog-editor-identity').getByRole('textbox', { name: 'Modelo', exact: true, includeHidden: true })).toHaveValue('Modelo anterior');
  expect(commandCount).toBe(0);
  await capture.getByRole('checkbox', { name: 'Incluir marca', exact: true }).uncheck();
  await capture.getByRole('button', { name: 'Aplicar al formulario', exact: true }).click();
  await expect(capture).not.toBeVisible();
  await expect(editor.getByRole('textbox', { name: 'Marca', exact: true })).toHaveValue('Marca conservada');
  await expect(editor.getByRole('textbox', { name: 'Modelo', exact: true })).toHaveValue('AC122CE');
  await expect(editor.getByRole('combobox', { name: 'Categoría', exact: true })).toHaveValue('air_conditioner');
  await expect(editor.getByRole('spinbutton', { name: 'Costo (RD$)', exact: true })).toHaveValue('100');
  await expect(editor.getByRole('spinbutton', { name: /^Precio final con ITBIS/ })).toHaveValue('150');
  await editor.locator('details[data-identification] summary').click();
  await expect(editor.getByRole('textbox', { name: /^Código de barras/ })).toHaveValue(internalCode);
  await expect(editor.getByRole('textbox', { name: 'Código adicional 1 de la variante 1', exact: true })).toHaveValue('6946087393113');
  expect(commandCount).toBe(0);
  expect(unexpected).toEqual([]);
});
