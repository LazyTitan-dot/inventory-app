import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';
import { PGlite } from '@electric-sql/pglite';

const migrations=fileURLToPath(new URL('../migrations/',import.meta.url));
const users=Object.fromEntries(['owner','admin','sales','inventory','viewer','outsider'].map((role,index)=>[role,`00000000-0000-4000-8000-00000000010${index}`]));

test('document lifecycle: stale edits, authoritative pricing, historical reconciliation and permissions',async()=>{
  const db=new PGlite();let checks=0;
  const check=(value,message)=>{assert.ok(value,message);checks++;};
  const equal=(actual,expected,message)=>{assert.deepEqual(actual,expected,message);checks++;};
  const scalar=async(sql,params=[])=>Object.values((await db.query(sql,params)).rows[0])[0];
  const as=async(role)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[users[role]??'']);if(role)await db.exec('set role authenticated');};
  const command=(action,payload,operation=randomUUID())=>scalar('select public.retail_command($1,$2,$3)',[operation,action,payload]);
  const reject=async(action,payload,pattern,op)=>{await assert.rejects(()=>command(action,payload,op),pattern);checks++;};
  const state=()=>scalar('select public.retail_bootstrap()');
  const document=async(id)=>(await state()).documents.find(d=>d.id===id);
  const item=async(id)=>(await state()).document_items.find(i=>i.document_id===id);
  const version=async(id)=>({id,expected_updated_at:(await document(id)).updated_at});
  const future=()=>new Date(Date.now()+86400000).toISOString();
  try {
    await db.exec(`create role anon nologin;create role authenticated nologin;create schema auth;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,banned_until timestamptz);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema auth to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;
      create schema storage;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text,unique(bucket_id,name));
      alter table storage.objects enable row level security;
      grant usage on schema storage to authenticated,anon;grant select,insert,update,delete on storage.objects to authenticated,anon;
      create function public.update_updated_at_column() returns trigger language plpgsql as $$begin new.updated_at=now();return new;end$$;
      create function public.set_updated_at() returns trigger language plpgsql as $$begin new.updated_at=now();return new;end$$;`);
    for(const name of (await readdir(migrations)).filter(n=>/retail_(core|commands|read_api|legacy_archive_import|deferred_constraint_security|document_lifecycle)\.sql$/.test(n)).sort())await db.exec(await readFile(`${migrations}/${name}`,'utf8'));
    for(const [role,id] of Object.entries(users)) {
      await db.query('insert into auth.users(id,email,email_confirmed_at) values($1,$2,now())',[id,`${role}@example.test`]);
      if(role!=='outsider')await db.query('insert into public.retail_memberships(user_id,email,role) values($1,$2,$3)',[id,`${role}@example.test`,role]);
    }
    const paths=(await db.query("select proconfig from pg_proc where oid in('public.set_updated_at()'::regprocedure,'public.update_updated_at_column()'::regprocedure)")).rows;
    check(paths.length===2&&paths.every(p=>p.proconfig.includes('search_path=""')),'Both optional legacy trigger functions have empty search_path');
    await db.exec("create table public.products(id text primary key,data jsonb);insert into public.products values('legacy-fixture','{}')");
    await as('owner');
    await reject('save_contact',{kind:'customer',name:'No crear antes del corte'},/actualización del negocio está en curso/);
    await reject('cancel_quote',{id:randomUUID(),reason:'No operar antes del corte'},/actualización del negocio está en curso/);
    await as();
    equal(Number(await scalar('select count(*) from public.retail_contacts')),0,'Pre-cutover guard rejects all writes before touching normalized data');
    await db.exec('delete from public.products');
    await as('owner');
    const product=(await command('save_product',{category:'tv',brand:'Marca',model:'Modelo',warranty_months:12,variants:[
      {name:'Negro',sku:'TV-NEGRO',cost:50,price:100,min_stock:1,reorder_target:4,opening_quantity:20},
      {name:'Blanco',sku:'TV-BLANCO',cost:30,price:0,min_stock:0,reorder_target:4,opening_quantity:2}
    ]})).entity_id;
    let snapshot=await state();
    const variant=snapshot.variants.find(v=>v.product_id===product&&v.sku==='TV-NEGRO').id;
    const pendingPrice=snapshot.variants.find(v=>v.product_id===product&&v.sku==='TV-BLANCO').id;
    const supplier=(await command('save_contact',{kind:'supplier',name:'Proveedor de prueba'})).entity_id;
    const customer=(await command('save_contact',{kind:'customer',name:'Cliente de prueba'})).entity_id;
    const quotePayload={items:[{variant_id:variant,quantity:2,expected_price:100}],contact_id:customer,expires_at:future(),notes:'Condiciones originales'};
    await reject('create_quote',{...quotePayload,items:[{variant_id:pendingPrice,quantity:1,expected_price:0}]},/precio pendiente/);
    await reject('create_sale',{items:[{variant_id:pendingPrice,quantity:1}],payment_method:'card'},/precio pendiente/);
    const freeQuote=await command('create_quote',{...quotePayload,discount:200});
    equal(freeQuote.result.total,0,'Authorized full discount is allowed over positive catalog prices');
    const q=(await command('create_quote',quotePayload)).entity_id;
    const original=await document(q);
    const stockBefore=(await state()).stocks;
    const movesBefore=(await state()).movements.length;
    const initialVersion=await version(q);
    await reject('update_quote',{...quotePayload,id:q},/Actualiza el documento/);
    await reject('update_quote',{...quotePayload,...initialVersion,items:[]},/entre 1 y 200/);
    equal(await document(q),original,'Failed edit preserves entire original quote');
    await reject('update_quote',{...quotePayload,...initialVersion,discount:1000},/discount/);
    await reject('update_quote',{...quotePayload,...initialVersion,items:[{variant_id:variant,quantity:2,expected_price:99}]},/precio.*cambió/);
    await reject('update_quote',{...quotePayload,...initialVersion,items:[{variant_id:pendingPrice,quantity:1}]},/precio pendiente/);
    const oldItems=(await state()).document_items.filter(i=>i.document_id===q);
    const documentsBefore=(await state()).documents.length;
    const editOp=randomUUID();
    const editPayload={...quotePayload,...initialVersion,items:[{variant_id:variant,quantity:3,expected_price:100}],discount:30,notes:'Condiciones revisadas'};
    const edited=await command('update_quote',editPayload,editOp);
    equal(edited.entity_id,q,'Editing keeps document identity');
    equal(edited.result.total,318.6,'Server recalculates authoritative discount and tax');
    equal(await command('update_quote',editPayload,editOp),edited,'Retry with original version returns cached result');
    await reject('update_quote',{...editPayload,discount:29},/ya se usó/,editOp);
    await reject('cancel_quote',{...initialVersion,reason:'Versión obsoleta'},/Otra persona/);
    const afterEdit=await document(q);
    equal(afterEdit.number,original.number,'Quote number is stable');
    equal(afterEdit.created_at,original.created_at,'Quote creation date is stable');
    equal(afterEdit.created_by,original.created_by,'Quote creator is stable');
    equal((await state()).documents.length,documentsBefore,'No temporary document remains');
    check(!(await state()).document_items.some(i=>oldItems.some(old=>old.id===i.id)),'Old quote lines are fully replaced');
    equal((await state()).stocks,stockBefore,'Quote editing does not move inventory');
    equal((await state()).movements.length,movesBefore,'Quote editing creates no movement');
    const nextQuote=(await command('create_quote',quotePayload)).entity_id;
    equal(Number((await document(nextQuote)).number.split('-')[1]),Number(original.number.split('-')[1])+1,'Quote edit does not consume a visible sequence number');
    const cancelPayload={...await version(q),reason:'Cliente cambió su decisión'};
    await reject('cancel_quote',{...cancelPayload,reason:''},/reason/);
    const cancelled=await command('cancel_quote',cancelPayload);
    equal(cancelled.result.status,'cancelled','Open quote can be cancelled');
    equal((await document(q)).status_reason,cancelPayload.reason,'Cancellation reason is retained separately from customer notes');
    equal((await document(q)).notes,'Condiciones revisadas','Cancelling does not overwrite commercial notes');
    await reject('update_quote',{...quotePayload,...await version(q)},/Solo puedes editar/);
    await reject('convert_quote',{id:q,payment_method:'card'},/no está abierta/);
    const converted=await command('convert_quote',{id:nextQuote,payment_method:'card'});
    check(Boolean(converted.entity_id),'Unaffected core quote conversion still works');
    await reject('update_quote',{...quotePayload,...await version(nextQuote)},/Solo puedes editar/);
    await reject('cancel_quote',{...await version(nextQuote),reason:'No válido'},/Solo puedes cancelar/);

    const openForRole=(await command('create_quote',quotePayload)).entity_id;
    const roleVersion=await version(openForRole);
    for(const role of ['inventory','viewer','outsider']) {
      await as(role);
      await reject('cancel_quote',{...roleVersion,reason:'Sin permiso'},/permiso|acceso|cuenta/i);
      await reject('update_quote',{...quotePayload,...roleVersion},/permiso|acceso|cuenta/i);
    }
    await as('sales');
    await reject('update_quote',{...quotePayload,...roleVersion,discount:200},/límite autorizado/);
    await command('update_quote',{...quotePayload,...roleVersion,notes:'Edición desde caja'});
    check(!(await state()).document_items.some(i=>'unit_cost' in i),'New quote workflow still hides costs from cashiers');
    equal((await state()).audit,[],'Audit before-state including costs is not disclosed to cashiers');
    await assert.rejects(()=>db.query('select retail_private.command_core($1,$2,$3)',[randomUUID(),'cancel_quote',{}]),/permission denied/);checks++;
    await assert.rejects(()=>db.query('select retail_private.update_quote($1,$2)',[quotePayload,randomUUID()]),/permission denied/);checks++;
    await assert.rejects(()=>db.query("update public.retail_documents set status='cancelled' where id=$1",[openForRole]),/permission denied/);checks++;

    await as('owner');
    const makeDraft=async({unlink=false,taxMismatch=false}={})=>{
      const id=(await command('create_purchase',{contact_id:supplier,items:[{variant_id:variant,quantity:2,unit_cost:40}],notes:'Condiciones históricas'})).entity_id;
      const current=await item(id);
      await as();
      await db.exec('begin');
      await db.query("update public.retail_documents set status='draft',legacy=jsonb_build_object('source','purchase_orders','id',$2::text),tax_rate=18,tax=$3,total=subtotal+$3 where id=$1",[id,randomUUID(),taxMismatch?17:0]);
      await db.query("update public.retail_document_items set variant_id=case when $2 then null else variant_id end,tax=$3,line_total=quantity*unit_price+$3,legacy=jsonb_build_object('source','purchase_orders','variant_match','unlinked') where id=$1",[current.id,unlink,taxMismatch?17:0]);
      await db.exec('commit');await as('owner');return id;
    };
    const draft=await makeDraft({taxMismatch:true});
    const draftBefore=await document(draft),lineBefore=await item(draft),draftVersion=await version(draft);
    const stockBeforeDraft=(await state()).stocks;
    await reject('confirm_purchase_draft',{id:draft},/Actualiza el documento/);
    await as('sales');
    await reject('confirm_purchase_draft',draftVersion,/permiso/);
    await as('inventory');
    const confirmOp=randomUUID();
    const confirmed=await command('confirm_purchase_draft',draftVersion,confirmOp);
    equal(confirmed.result.status,'pending','Inventory role can confirm a fully linked draft');
    equal(await command('confirm_purchase_draft',draftVersion,confirmOp),confirmed,'Draft confirmation is idempotent');
    const pending=await document(draft);
    for(const field of ['subtotal','discount','tax_rate','tax','total','contact_snapshot','notes','legacy','created_at'])equal(pending[field],draftBefore[field],`Draft confirmation preserves ${field}`);
    equal(await item(draft),lineBefore,'Draft confirmation does not alter historical line or tax disagreement');
    equal((await state()).stocks,stockBeforeDraft,'Draft confirmation has no stock effect');
    await reject('confirm_purchase_draft',await version(draft),/Solo puedes confirmar/);
    await command('receive_purchase',{id:draft,items:[{item_id:lineBefore.id,quantity:1}]});
    equal((await document(draft)).status,'partial','Confirmed draft can subsequently receive one actual unit');
    const stockAfterReceipt=(await state()).stocks;
    await command('cancel_purchase',{...await version(draft),reason:'Proveedor no enviará el saldo'});
    equal((await state()).stocks,stockAfterReceipt,'Cancelling remaining purchase preserves already received stock');
    equal((await item(draft)).received_quantity,1,'Cancellation preserves receipt history');

    await as('owner');
    const toCancel=await makeDraft();
    await reject('cancel_purchase',{...await version(toCancel),reason:''},/reason/);
    await command('cancel_purchase',{...await version(toCancel),reason:'Borrador duplicado'});
    equal((await document(toCancel)).status,'cancelled','Draft purchase may be cancelled without confirming it');
    await reject('confirm_purchase_draft',await version(toCancel),/Solo puedes confirmar/);
    await reject('cancel_purchase',{...await version(toCancel),reason:'Repetida'},/ya fue recibida o cancelada/);
    const unlinked=await makeDraft({unlink:true});
    const orphan=await item(unlinked),unlinkedVersion=await version(unlinked);
    await reject('confirm_purchase_draft',unlinkedVersion,/Vincula cada artículo/);
    const linkPayload={item_id:orphan.id,variant_id:variant,expected_updated_at:unlinkedVersion.expected_updated_at,reason:'Marca, modelo, variante y SKU comprobados en factura original'};
    await as('inventory');await reject('link_historical_item',linkPayload,/permiso/);
    await as('sales');await reject('link_historical_item',linkPayload,/permiso/);
    await as('owner');
    await reject('link_historical_item',{...linkPayload,variant_id:pendingPrice},/deben coincidir/);
    await reject('link_historical_item',{...linkPayload,reason:''},/reason/);
    const linkOp=randomUUID();
    const linked=await command('link_historical_item',linkPayload,linkOp);
    equal(linked.result.variant_id,variant,'Explicit verified link returns selected variant');
    equal((await item(unlinked)).variant_id,variant,'Explicit verified link actually updates the stored foreign key');
    equal((await item(unlinked)).product_snapshot,orphan.product_snapshot,'Historical snapshot remains intact after relinking');
    equal((await item(unlinked)).unit_cost,orphan.unit_cost,'Relinking does not replace historical cost with current cost');
    equal(await command('link_historical_item',linkPayload,linkOp),linked,'Link operation is idempotent');
    await reject('confirm_purchase_draft',unlinkedVersion,/Otra persona/);
    await command('confirm_purchase_draft',await version(unlinked));
    equal((await document(unlinked)).status,'pending','Confirmed identity resolves historical draft safely');
    await reject('link_historical_item',{...linkPayload,expected_updated_at:(await document(unlinked)).updated_at},/todavía no tenga variante/);

    const historicalSale=(await command('create_sale',{items:[{variant_id:variant,quantity:1}],payment_method:'card'})).entity_id;
    await as();
    await db.query("update public.retail_documents set status='legacy_pending',legacy=jsonb_build_object('source','sales','id','synthetic-pending','original_status','pending') where id=$1",[historicalSale]);
    await as('owner');
    const pendingSaleVersion=await version(historicalSale);
    const closeHistorical={...pendingSaleVersion,reason:'Operación histórica cancelada, inventario físico conciliado',stock_already_accounted:true,stock_effect:'none'};
    const stockBeforeClose=(await state()).stocks,movementCountBeforeClose=(await state()).movements.length;
    await reject('cancel_legacy_sale',{...closeHistorical,stock_already_accounted:false},/Confirma expresamente/);
    await reject('cancel_legacy_sale',{...closeHistorical,stock_effect:'restore'},/Confirma expresamente/);
    await as('sales');await reject('cancel_legacy_sale',closeHistorical,/permiso/);
    await as('admin');
    const closeOp=randomUUID(),closed=await command('cancel_legacy_sale',closeHistorical,closeOp);
    equal(closed.result.status,'voided','Administrator can close explicitly reconciled pending legacy sale');
    equal(await command('cancel_legacy_sale',closeHistorical,closeOp),closed,'Historical cancellation is idempotent');
    equal((await state()).stocks,stockBeforeClose,'Historical administrative cancellation never replays stock');
    equal((await state()).movements.length,movementCountBeforeClose,'Historical administrative cancellation creates no synthetic stock ledger');
    check((await document(historicalSale)).legacy.cancelled_without_stock_movement,'Audit-facing historical declaration retained');
    await reject('void_sale',{id:historicalSale,reason:'No debe reponer'},/anular|anulada/);
    await reject('return_sale',{id:historicalSale,items:[{item_id:(await item(historicalSale)).id,quantity:1,condition:'available'}],reason:'No debe reembolsar',payment_method:'card'},/no admite/);
    const audit=(await state()).audit;
    const editAudit=audit.find(a=>a.operation_id===editOp);
    equal(editAudit.details.before.document.notes,'Condiciones originales','Quote audit stores original commercial conditions');
    check(audit.some(a=>a.action==='link_historical_item'&&a.details.payload.reason===linkPayload.reason),'Historical linkage actor and evidence are audited');
    equal(audit.filter(a=>a.operation_id===closeOp).length,1,'Retry creates no duplicate audit entry');

    await as();
    await db.exec('begin');
    await as('owner');
    await command('create_quote',quotePayload);
    await db.exec('set constraints all immediate');
    await db.exec('rollback');
    checks++;
    await as();
    check(Number(await scalar("select count(*) from public.retail_document_items i left join public.retail_documents d on d.id=i.document_id where d.id is null"))===0,'No orphaned document items');
    check(Number(await scalar('select count(*) from public.retail_stocks where available<0 or quarantine<0'))===0,'No negative inventory');
    console.log(`Document lifecycle: ${checks} assertions passed; synthetic database only.`);
  } finally {await db.close();}
});
